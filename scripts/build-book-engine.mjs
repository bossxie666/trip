import { build } from "vite";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";

const scene = await readFile("public/assets/travel-desk/scene.js", "utf8");
const names = [...new Set([...scene.matchAll(/T\.([A-Za-z][A-Za-z0-9_]*)/g)].map(match => match[1]))].sort();
await mkdir("work", { recursive: true });
await writeFile("work/book-engine-entry.js", `export {${names.join(",")}} from "../public/assets/travel-desk/vendor/three.module.js";\n`);
const result = await build({ configFile: false, publicDir: false, logLevel: "silent", build: {
  write: false, minify: true, target: "es2020", lib: { entry: "work/book-engine-entry.js", formats: ["es"] },
} });
const output = (Array.isArray(result) ? result[0] : result).output.find(item => item.type === "chunk");
const code = "/**\n * @license Copyright 2010-2024 Three.js Authors\n * SPDX-License-Identifier: MIT\n * Generated by scripts/build-book-engine.mjs from the bundled r170 source.\n */\n" + output.code;
await writeFile("public/assets/travel-desk/vendor/book-engine.min.js", code);
console.log(JSON.stringify({ exports: names.length, bytes: Buffer.byteLength(code), gzipBytes: gzipSync(code).length }));
